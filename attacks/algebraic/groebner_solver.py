def generate_polygen_equations(
    plaintexts: List[int],
    ciphertexts: List[int],
    rounds: int,
    project_root: str = None,
    key_offsets: List[int] = None
) -> List[str]:
    """
    Generate KeeLoq equations using the C polygen implementation.
    
    This mirrors the equation format in polygen.c:
    - EQ1: L_i_j + constant (for plaintext/ciphertext constraints)
    - EQ2: Round function with NLF expanded
    - EQ3: a_i_j + L_i_(j-1)*L_i_(j-6) (auxiliary)
    - EQ4: b_i_j + L_i_(j-1)*L_i_(j-31) (auxiliary)
    
    Args:
        plaintexts: List of plaintext values
        ciphertexts: List of ciphertext values
        rounds: Number of rounds
        project_root: Path to KeeLoq project root (for finding the C binary)
        key_offsets: List of key schedule offsets per pair (default: all 0)
    
    Returns:
        List of equation strings in polygen format
    """
    equations = []
    num_pairs = len(plaintexts)
    if key_offsets is None:
        key_offsets = [0] * num_pairs
    
    for i in range(num_pairs):
        pt = plaintexts[i]
        ct = ciphertexts[i]
        ko = key_offsets[i]
        
        # EQ1: Initial state = plaintext bits
        for j in range(32):
            bit = (pt >> j) & 1
            equations.append(f"L_{i}_{j} + {bit}")
        
        # Round function equations
        for j in range(32, rounds + 32):
            # EQ2: Main round equation (NLF expanded as ANF)
            # Matches exactly the format in polygen.c/polygen.h
            eq2 = (
                f"L_{i}_{j} + k_{((j-32) + ko) % 64} + L_{i}_{j-32} + L_{i}_{j-16} + L_{i}_{j-23}"
                f" + L_{i}_{j-31} + L_{i}_{j-1}*L_{i}_{j-12} + b_{i}_{j} + L_{i}_{j-6}*L_{i}_{j-12}"
                f" + L_{i}_{j-6}*L_{i}_{j-31} + L_{i}_{j-12}*L_{i}_{j-23} + L_{i}_{j-23}*L_{i}_{j-31}"
                f" + b_{i}_{j}*L_{i}_{j-23} + b_{i}_{j}*L_{i}_{j-12} + a_{i}_{j}*L_{i}_{j-23} + a_{i}_{j}*L_{i}_{j-12}"
            )
            equations.append(eq2)
            
            # EQ3: Auxiliary variable a
            equations.append(f"a_{i}_{j} + L_{i}_{j-1}*L_{i}_{j-6}")
            
            # EQ4: Auxiliary variable b  
            equations.append(f"b_{i}_{j} + L_{i}_{j-1}*L_{i}_{j-31}")
        
        # EQ1: Final state = ciphertext bits
        for j in range(rounds, rounds + 32):
            bit = (ct >> (j - rounds)) & 1
            equations.append(f"L_{i}_{j} + {bit}")
    
    return equations


def parse_polygen_equations(equations: List[str], rounds: int, num_pairs: int):
    """
    Parse polygen equation strings and build a polynomial system.
    
    Args:
        equations: List of equation strings from polygen
        rounds: Number of rounds
        num_pairs: Number of P/C pairs
    
    Returns:
        ring: BooleanPolynomialRing
        polys: List of polynomials
        key_names: Key variable names
    """
    # Collect all variable names from the equations
    var_pattern = re.compile(r'[Lkab]_?\d+(?:_\d+)?')
    all_vars = set()
    
    for eq in equations:
        matches = var_pattern.findall(eq)
        all_vars.update(matches)
    
    # Categorize variables
    key_vars = sorted([v for v in all_vars if v.startswith('k_')], 
                      key=lambda x: int(x.split('_')[1]))
    L_vars = sorted([v for v in all_vars if v.startswith('L_')],
                    key=lambda x: (int(x.split('_')[1]), int(x.split('_')[2])))
    a_vars = sorted([v for v in all_vars if v.startswith('a_')],
                    key=lambda x: (int(x.split('_')[1]), int(x.split('_')[2])))
    b_vars = sorted([v for v in all_vars if v.startswith('b_')],
                    key=lambda x: (int(x.split('_')[1]), int(x.split('_')[2])))
    
    # Create ordered variable list (key vars first for extraction)
    all_var_names = key_vars + L_vars + a_vars + b_vars
    
    # Create Boolean polynomial ring
    ring = BooleanPolynomialRing(len(all_var_names), all_var_names)
    var_dict = {str(v): v for v in ring.gens()}
    
    # Parse equations into polynomials
    polys = []
    for eq_str in equations:
        poly = parse_equation_to_poly(eq_str, ring, var_dict)
        if poly is not None:
            polys.append(poly)
    
    return ring, polys, key_vars


def parse_equation_to_poly(eq_str: str, ring, var_dict):
    """
    Parse a single polygen equation string into a polynomial.
    
    Handles formats like:
    - "L_0_0 + 1"
    - "L_0_32 + k_0 + L_0_0 + L_0_16 + L_0_9*L_0_1 + ..."
    """
    # Replace variable names with ring generators
    # Split by + and process each term
    terms = [t.strip() for t in eq_str.split('+')]
    
    poly = ring.zero()
    
    for term in terms:
        if not term:
            continue
        
        # Check if it's a constant
        if term.isdigit():
            if int(term) == 1:
                poly += ring.one()
            continue
        
        # Parse product of variables (e.g., "L_0_1*L_0_6")
        factors = term.split('*')
        term_poly = ring.one()
        
        for factor in factors:
            factor = factor.strip()
            if factor in var_dict:
                term_poly *= var_dict[factor]
            elif factor.isdigit():
                if int(factor) == 0:
                    term_poly = ring.zero()
                    break
            else:
                # Unknown variable - skip this equation
                return None
        
        poly += term_poly
    
    return poly


def build_keeloq_system(
    plaintexts: list,
    ciphertexts: list,
    rounds: int,
    use_boolean_ring: bool = True,
    key_offsets: list = None
):
    """
    Build the polynomial system for KeeLoq over GF(2).
    
    Supports multiple plaintext-ciphertext pairs for better key recovery.
    
    Variables:
        - k_0, ..., k_63: key bits (shared across all pairs)
        - L_p_0, ..., L_p_{31+rounds}: state bits for pair p
    
    Args:
        plaintexts: list of plaintext values
        ciphertexts: list of ciphertext values  
        rounds: number of rounds per constraint
        use_boolean_ring: use BooleanPolynomialRing (default True)
        key_offsets: list of key schedule offsets per pair (default: all 0)
    
    Returns:
        ring: polynomial ring
        polys: list of polynomials
        key_vars: key variable names for solution extraction
    """
    num_pairs = len(plaintexts)
    num_state_vars = 32 + rounds
    if key_offsets is None:
        key_offsets = [0] * num_pairs
    
    # Variable names: key vars shared, state vars per pair
    key_names = [f'k{i}' for i in range(64)]
    state_names = []
    for p in range(num_pairs):
        state_names.extend([f'L{p}_{i}' for i in range(num_state_vars)])
    all_names = key_names + state_names
    
    # Create ring over GF(2)
    if use_boolean_ring:
        # BooleanPolynomialRing automatically enforces x^2 = x
        ring = BooleanPolynomialRing(len(all_names), all_names)
    else:
        ring = PolynomialRing(GF(2), all_names)
    
    # Get variables
    gens = ring.gens()
    k = gens[:64]  # key bits (shared)
    
    polys = []
    
    # Build constraints for each plaintext-ciphertext pair
    for p in range(num_pairs):
        # State variables for this pair
        offset = 64 + p * num_state_vars
        L = gens[offset:offset + num_state_vars]
        
        plaintext = plaintexts[p]
        ciphertext = ciphertexts[p]
        
        # Initial state constraints (plaintext bits)
        for j in range(32):
            pt_bit = (plaintext >> j) & 1
            polys.append(L[j] + pt_bit)
        
        # Round function equations
        for i in range(rounds):
            j = 32 + i  # current state index
            
            # NLF inputs (bit positions in state)
            x4 = L[j - 1]      # bit 31 of previous state
            x3 = L[j - 6]      # bit 26
            x2 = L[j - 12]     # bit 20
            x1 = L[j - 23]     # bit 9
            x0 = L[j - 31]     # bit 1
            
            # NLF output
            nlf_poly = create_nlf_polynomial(ring, x4, x3, x2, x1, x0)
            
            # Key bit (cyclic, with per-pair offset)
            key_bit = k[(i + key_offsets[p]) % 64]
            
            # Feedback: new_bit = k[i] + L[16] + L[0] + NLF
            feedback = key_bit + L[j - 16] + L[j - 32] + nlf_poly
            
            # After shift: L[j] is the new MSB (bit 31)
            polys.append(L[j] + feedback)
        
        # Final state constraints (ciphertext bits)
        for j in range(32):
            ct_bit = (ciphertext >> j) & 1
            state_idx = rounds + j  # L[rounds] to L[rounds+31]
            polys.append(L[state_idx] + ct_bit)
    
    return ring, polys, key_names


def solve_with_groebner(ring, polys, key_names, verbose: bool = True, target_key: int = None):
    """
    Solve the polynomial system using Groebner basis.
    
    Returns the recovered key if successful, None otherwise.
    """
    if verbose:
        print(f"Building ideal with {len(polys)} polynomials...")
    
    # Create ideal
    I = Ideal(polys)
    
    if verbose:
        print("Computing Groebner basis (this may take a while)...")
    
    start = time.time()
    
    # Compute Groebner basis
    try:
        G = I.groebner_basis()
    except Exception as e:
        print(f"Groebner basis computation failed: {e}")
        return None
    
    elapsed = time.time() - start
    
    if verbose:
        print(f"Groebner basis computed in {elapsed:.2f}s")
        print(f"Basis has {len(G)} polynomials")
    
    # Check if system has a solution (basis != [1])
    if len(G) == 1 and G[0] == 1:
        if verbose:
            print("System is inconsistent (no solution)")
        return None
    
    # Extract key bits from univariate polynomials in the Groebner basis
    # Supports both naming conventions: k0 (default) and k_0 (polygen)
    key_bits = {}
    
    for poly in G:
        poly_vars = poly.variables()
        if len(poly_vars) == 1:
            var = poly_vars[0]
            var_str = str(var)
            
            # Try both naming conventions
            idx = None
            if var_str.startswith('k_') and var_str[2:].isdigit():
                # Polygen format: k_0, k_1, ...
                idx = int(var_str[2:])
            elif var_str.startswith('k') and var_str[1:].isdigit():
                # Default format: k0, k1, ...
                idx = int(var_str[1:])
            
            if idx is not None:
                # poly = ki + c, where c is constant
                # poly = 0 => ki = c
                constant = poly.constant_coefficient()
                key_bits[idx] = int(constant)
    
    if verbose:
        print(f"Recovered {len(key_bits)}/64 key bits from basis")
        if key_bits:
            # Show which bits we recovered
            recovered = sorted(key_bits.keys())
            print(f"Recovered bit indices: {recovered[:10]}{'...' if len(recovered) > 10 else ''}")
    
    # Verify partial recovery against target key if provided
    if key_bits and target_key is not None:
        correct = sum(1 for i, b in key_bits.items() if ((target_key >> i) & 1) == b)
        if verbose:
            print(f"Verification: {correct}/{len(key_bits)} recovered bits match target key")
    
    if len(key_bits) == 64:
        key = sum(bit << i for i, bit in key_bits.items())
        return key
    
    if verbose and len(key_bits) < 64:
        print("System underdetermined - try more rounds or multiple P/C pairs")
    
    return None


