# KeeLoq NLF lookup constant
NLF_CONSTANT = 0x3A5C742E


def nlf(x4: int, x3: int, x2: int, x1: int, x0: int) -> int:
    """KeeLoq Non-Linear Function (5-input, 1-output)."""
    index = (x4 << 4) | (x3 << 3) | (x2 << 2) | (x1 << 1) | x0
    return (NLF_CONSTANT >> index) & 1


def keeloq_encrypt(key: int, plaintext: int, rounds: int = 528) -> int:
    """KeeLoq encryption (for verification)."""
    state = plaintext
    for i in range(rounds):
        nlf_out = nlf(
            (state >> 31) & 1,
            (state >> 26) & 1,
            (state >> 20) & 1,
            (state >> 9) & 1,
            (state >> 1) & 1,
        )
        key_bit = (key >> (i % 64)) & 1
        feedback = key_bit ^ ((state >> 16) & 1) ^ (state & 1) ^ nlf_out
        state = ((state >> 1) | (feedback << 31)) & 0xFFFFFFFF
    return state


def create_nlf_polynomial(ring, x4, x3, x2, x1, x0):
    """
    Create algebraic normal form (ANF) of the KeeLoq NLF.
    
    NLF(a,b,c,d,e) = d + e + ac + ae + bc + be + cd + de + ade + ace + abd + abc
    
    This is derived from the truth table defined by NLF_CONSTANT = 0x3A5C742E
    """
    # ANF of NLF (computed from truth table)
    return (
        x1 + x0 +
        x4*x2 + x4*x0 +
        x3*x2 + x3*x0 +
        x2*x1 + x1*x0 +
        x4*x1*x0 + x4*x2*x0 +
        x4*x3*x1 + x4*x3*x2
    )


